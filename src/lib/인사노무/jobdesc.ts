export const shareSum = (j: JobDesc) => j.tasks.reduce((s, x) => s + (Number(x.share) || 0), 0);

/** 저장 전 정리 (서버) */
export function cleanJob(j: Partial<JobDesc>): JobDesc {
  const s = (x: unknown, n = 300) => String(x ?? "").trim().slice(0, n);
  const list = (x: unknown) => (Array.isArray(x) ? x : String(x ?? "").split("\n")).map((v) => s(v, 200)).filter(Boolean).slice(0, 30);
  return {
    id: s(j.id, 40) || `jd-${Date.now()}`, name: s(j.name, 60), units: (j.units ?? []).map((u) => s(u, 40)).filter(Boolean),
    grade: s(j.grade, 60), reportTo: s(j.reportTo, 60), ncs: s(j.ncs, 200), purpose: s(j.purpose, 600),
    tasks: (j.tasks ?? []).map((x) => ({ name: s(x.name, 100), detail: s(x.detail, 300), share: Math.max(0, Math.min(100, Math.round(Number(x.share) || 0))), cycle: s(x.cycle, 10) }))
      .filter((x) => x.name).slice(0, 15),
    authority: s(j.authority, 400), knowledge: list(j.knowledge), skills: list(j.skills), attitudes: list(j.attitudes),
    basics: (j.basics ?? []).filter((b) => BASICS.includes(b)), edu: s(j.edu, 120), career: s(j.career, 120), licenses: list(j.licenses),
    env: s(j.env, 400), kpis: list(j.kpis), training: list(j.training), updated: s(j.updated, 10), writer: s(j.writer, 30),
  };
}
