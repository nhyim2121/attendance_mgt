-- ---------------------------------------------------------------- 한 번에 처리해야 하는 작업 (호출한 사용자 권한으로 실행)

-- 캡스 기록 저장: 이미 있는 기록(출입일시·이름·모드 같음)은 건너뛰고 새로 들어간 건수를 돌려준다.
create function public.save_caps(p_rows jsonb, p_file text, p_sheet text, p_period text, p_user text)
returns integer language plpgsql security invoker set search_path = public as $$
declare
  v_upload bigint;
  v_added integer;
begin
  insert into uploads (kind, file, sheet, count, period, user_id)
  values ('캡스', p_file, p_sheet, jsonb_array_length(p_rows), p_period, p_user)
  returning id into v_upload;

  insert into records (ts, name, emp_id, dept, door, mode, auth, work_type, place, note, upload_id)
  select r.ts, r.name, coalesce(r.emp_id, ''), coalesce(r.dept, ''), coalesce(r.door, ''), coalesce(r.mode, ''),
         coalesce(r.auth, ''), coalesce(r.work_type, ''), coalesce(r.place, ''), coalesce(r.note, ''), v_upload
  from jsonb_to_recordset(p_rows) as r(ts timestamp, name text, emp_id text, dept text, door text, mode text,
                                       auth text, work_type text, place text, note text)
  on conflict (ts, name, mode) do nothing;
  get diagnostics v_added = row_count;

  update uploads set added = v_added where id = v_upload;
  return v_added;
end $$;

-- 근태현황 파일은 1월부터 누적된 파일이라 올릴 때마다 명단·근태를 통째로 교체한다.
create function public.replace_hiworks(p_roster jsonb, p_leaves jsonb, p_file text, p_user text)
returns void language plpgsql security invoker set search_path = public as $$
declare
  v_n integer := jsonb_array_length(p_leaves);
begin
  if jsonb_array_length(p_roster) > 0 then
    delete from roster where true;
    insert into roster (ord, dept, name)
    select r.ord, coalesce(r.dept, ''), r.name
    from jsonb_to_recordset(p_roster) as r(ord integer, dept text, name text)
    on conflict (name) do nothing;
  end if;
  delete from leaves where true;
  insert into leaves (day, name, dept, rank, type, content, note, sheet)
  select r.day, r.name, coalesce(r.dept, ''), coalesce(r.rank, ''), r.type, coalesce(r.content, ''),
         coalesce(r.note, ''), coalesce(r.sheet, '')
  from jsonb_to_recordset(p_leaves) as r(day date, name text, dept text, rank text, type text, content text,
                                         note text, sheet text);
  insert into uploads (kind, file, sheet, count, added, period, user_id)
  values ('근태현황', p_file, '명단 ' || jsonb_array_length(p_roster) || '명', v_n, v_n,
          coalesce((select min(day)::text || ' ~ ' || max(day)::text from leaves), '-'), p_user);
end $$;

-- 업로드 하나로 들어온 캡스 기록 삭제 (관리자)
create function public.delete_upload(p_id bigint)
returns integer language plpgsql security invoker set search_path = public as $$
declare v_n integer;
begin
  if not is_admin() then raise exception '관리자만 삭제할 수 있습니다.'; end if;
  delete from records where upload_id = p_id;
  get diagnostics v_n = row_count;
  delete from uploads where id = p_id;
  return v_n;
end $$;

-- 'YYYY-MM' 달의 캡스 기록 삭제 (관리자)
create function public.delete_month(p_month text)
returns integer language plpgsql security invoker set search_path = public as $$
declare
  v_n integer;
  v_start timestamp := to_timestamp(p_month || '-01', 'YYYY-MM-DD')::timestamp;
begin
  if not is_admin() then raise exception '관리자만 삭제할 수 있습니다.'; end if;
  delete from records where ts >= v_start and ts < v_start + interval '1 month';
  get diagnostics v_n = row_count;
  return v_n;
end $$;

-- 보고서 저장: 그날 행을 통째로 교체 (발송 기록은 유지)
create function public.save_report(p_day date, p_rows jsonb, p_user text)
returns void language plpgsql security invoker set search_path = public as $$
begin
  delete from report_rows where day = p_day;
  insert into report_rows (day, section, ord, dept, rank, name, types, title, detail, value, note)
  select p_day, r.section, coalesce(r.ord, 0), coalesce(r.dept, ''), coalesce(r.rank, ''), coalesce(r.name, ''),
         coalesce(r.types, ''), coalesce(r.title, ''), coalesce(r.detail, ''), coalesce(r.value, ''),
         coalesce(r.note, '')
  from jsonb_to_recordset(p_rows) as r(section text, ord integer, dept text, rank text, name text, types text,
                                       title text, detail text, value text, note text);
  insert into reports (day, author, updated_at) values (p_day, p_user, now())
  on conflict (day) do update set author = excluded.author, updated_at = excluded.updated_at;
end $$;

-- 직원 명부 저장: 통째로 교체 (추가·수정·삭제 모두 반영)
create function public.save_employees(p_rows jsonb, p_user text)
returns integer language plpgsql security invoker set search_path = public as $$
begin
  delete from employees where true;
  insert into employees (name, caps_name, emp_id, dept, rank, join_date, leave_date, note, ord, edited_by)
  select r.name, coalesce(r.caps_name, ''), coalesce(r.emp_id, ''), coalesce(r.dept, ''), coalesce(r.rank, ''),
         r.join_date, r.leave_date, coalesce(r.note, ''), r.ord, p_user
  from jsonb_to_recordset(p_rows) as r(name text, caps_name text, emp_id text, dept text, rank text,
                                       join_date date, leave_date date, note text, ord integer);
  return jsonb_array_length(p_rows);
end $$;

-- 기록이 있는 달 목록과 전체 기간
create function public.record_months()
returns table (month text, first_day date, last_day date, n bigint)
language sql stable security invoker set search_path = public as $$
  select to_char(ts, 'YYYY-MM'), min(ts)::date, max(ts)::date, count(*)
  from records group by 1 order by 1;
$$;

-- 이름별 첫·마지막 출입일 (입사·퇴사일 참고용)
create function public.record_name_span()
returns table (name text, first_day date, last_day date)
language sql stable security invoker set search_path = public as $$
  select name, min(ts)::date, max(ts)::date from records group by name;
$$;
