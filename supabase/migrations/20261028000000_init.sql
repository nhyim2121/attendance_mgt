-- 근태관리통합시스템 공용 저장소
-- 로그인한 관리팀(authenticated)만 읽고 쓴다. 삭제·계정 관리는 관리자만.

-- ---------------------------------------------------------------- 계정
create table public.profiles (
  id uuid primary key references auth.users on delete cascade,
  login_id text unique not null,
  name text not null,
  role text not null check (role in ('관리자', '담당자')),
  created_at timestamptz not null default now()
);

-- 이전(Streamlit) 계정: 처음 로그인할 때 PBKDF2 비밀번호를 확인하고 Supabase 계정으로 옮긴 뒤 지운다.
create table public.legacy_users (
  login_id text primary key,
  name text not null,
  role text not null,
  hash text not null,
  created_at text
);

create function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from profiles where id = auth.uid() and role = '관리자');
$$;

-- ---------------------------------------------------------------- 캡스 기록·업로드
create table public.uploads (
  id bigint generated by default as identity primary key,
  kind text not null,              -- '캡스' | '근태현황'
  file text not null default '',
  sheet text not null default '',
  count integer not null default 0,
  added integer,
  period text not null default '',
  user_id text not null default '',
  created_at timestamptz not null default now()
);

create table public.records (
  id bigint generated always as identity primary key,
  ts timestamp not null,           -- 출입일시 (현지 시각, 시간대 없음)
  name text not null,
  emp_id text not null default '',
  dept text not null default '',
  door text not null default '',
  mode text not null default '',
  auth text not null default '',
  work_type text not null default '',
  place text not null default '',
  note text not null default '',
  upload_id bigint,
  unique (ts, name, mode)
);
create index records_ts_idx on public.records (ts);
create index records_upload_idx on public.records (upload_id);

-- ---------------------------------------------------------------- 명단·하이웍스 근태
